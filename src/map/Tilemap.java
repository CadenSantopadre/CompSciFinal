    private final int[][] mapData;

    public Tilemap(int[][] mapData) {
        this.mapData = mapData;
    }

    public static Tilemap[] getStages() {
        return new Tilemap[] {new Tilemap(FINAL_DESTINATION_LARGE), new Tilemap(BATTLEFIELD_LARGE), new Tilemap(SMASHVILLE_LARGE), new Tilemap(HYRULE_TEMPLE_LARGE)};
    }

    public int getColumnCount() {
        return mapData[0].length;
    }

    public int getRowCount() {
        return mapData.length;
    }

    public boolean isTileSolid(int col, int row) {
        if (row < 0 || row >= mapData.length || col < 0 || col >= mapData[row].length) {
            return false;
        }
        return mapData[row][col] == 1;
    }

    public Rectangle getTileBounds(int col, int row, int screenWidth, int screenHeight) {
        int mapWidth = mapData[0].length * TILE_SIZE;
        int mapHeight = mapData.length * TILE_SIZE;
        int originX = (screenWidth - mapWidth) / 2;
        int originY = screenHeight - mapHeight;
        return new Rectangle(originX + col * TILE_SIZE, originY + row * TILE_SIZE, TILE_SIZE, TILE_SIZE);
    }

    public void draw(Graphics2D g2, int screenWidth, int screenHeight) {
        draw(g2, (screenWidth - mapData[0].length * TILE_SIZE) / 2,
                screenHeight - mapData.length * TILE_SIZE, TILE_SIZE);
    }

    public void drawPreview(Graphics2D g2, int x, int y, int tileSize) {
        draw(g2, x, y, tileSize);
    }

    private void draw(Graphics2D g2, int x, int y, int tileSize) {
        g2.setColor(Color.GREEN);
        for (int row = 0; row < mapData.length; row++) {
            for (int col = 0; col < mapData[row].length; col++) {
                if (mapData[row][col] == 1) {
                    g2.fillRect(x + col * tileSize, y + row * tileSize, tileSize, tileSize);
                }
            }
        }
    }
